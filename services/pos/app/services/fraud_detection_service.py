    async def run_daily_fraud_analysis(
        self,
        venue_id: uuid.UUID,
        target_date: date,
    ) -> List[FraudAlert]:
        """
        Run comprehensive fraud analysis for a specific date.

        Executes all fraud detection rules and generates alerts for any
        suspicious activity detected. This is typically run as a batch
        job at the end of each business day.

        Args:
            venue_id: The venue to analyze.
            target_date: The date to analyze.

        Returns:
            List of FraudAlerts generated during analysis.
        """
        logger.info(
            "daily_fraud_analysis_started",
            venue_id=str(venue_id),
            target_date=str(target_date),
        )

        alerts: List[FraudAlert] = []

        # Get all cashiers who worked on this date
        cashier_query = (
            select(Transaction.cashier_id)
            .where(
                and_(
                    Transaction.venue_id == venue_id,
                    func.date(Transaction.created_at) == target_date,
                    Transaction.cashier_id.isnot(None),
                )
            )
            .distinct()
        )

        result = await self.db.execute(cashier_query)
        cashier_ids = [row[0] for row in result.fetchall()]

        # Run cashier-specific checks
        for cashier_id in cashier_ids:
            # High void rate
            alert = await self.check_high_void_rate(venue_id, cashier_id)
            if alert:
                alerts.append(alert)

            # Unusual refund patterns
            alert = await self.check_unusual_refund_pattern(venue_id, cashier_id)
            if alert:
                alerts.append(alert)

            # Excessive comps
            alert = await self.check_excessive_comps(venue_id, cashier_id)
            if alert:
                alerts.append(alert)

            # Repeated voids
            alert = await self.check_repeated_voids(venue_id, cashier_id)
            if alert:
                alerts.append(alert)

        # Check cash drawers closed on this date
        drawer_query = select(CashDrawer).where(
            and_(
                CashDrawer.venue_id == venue_id,
                func.date(CashDrawer.closed_at) == target_date,
                CashDrawer.status == CashDrawerStatus.CLOSED.value,
            )
        )

        drawer_result = await self.db.execute(drawer_query)
        drawers = drawer_result.scalars().all()

        for drawer in drawers:
            alert = await self.check_cash_drawer_variance(venue_id, drawer.id)
            if alert:
                alerts.append(alert)

        # Check for split transactions
        split_alerts = await self.check_split_transactions(venue_id)
        alerts.extend(split_alerts)

        logger.info(
            "daily_fraud_analysis_completed",
            venue_id=str(venue_id),
            target_date=str(target_date),
            alerts_generated=len(alerts),
        )

        return alerts

    async def get_fraud_summary(
        self,
        venue_id: uuid.UUID,
        date_from: date,
        date_to: date,
    ) -> Dict[str, Any]:
        """
        Generate a fraud alert summary for a date range.

        Provides aggregate statistics on fraud alerts including counts
        by status, severity, and type, as well as resolution metrics.

        Args:
            venue_id: The venue to summarize.
            date_from: Start date (inclusive).
            date_to: End date (inclusive).

        Returns:
            Dictionary containing summary statistics.
        """
        base_filter = and_(
            FraudAlert.venue_id == venue_id,
            func.date(FraudAlert.created_at) >= date_from,
            func.date(FraudAlert.created_at) <= date_to,
        )

        # Total count
        total_query = select(func.count(FraudAlert.id)).where(base_filter)
        total_result = await self.db.execute(total_query)
        total_alerts = total_result.scalar() or 0

        # Counts by status
        status_query = (
            select(
                FraudAlert.status,
                func.count(FraudAlert.id).label("count"),
            )
            .where(base_filter)
            .group_by(FraudAlert.status)
        )
        status_result = await self.db.execute(status_query)
        by_status = {row.status: row.count for row in status_result.fetchall()}

        # Counts by severity
        severity_query = (
            select(
                FraudAlert.severity,
                func.count(FraudAlert.id).label("count"),
            )
            .where(base_filter)
            .group_by(FraudAlert.severity)
        )
        severity_result = await self.db.execute(severity_query)
        by_severity = {row.severity: row.count for row in severity_result.fetchall()}

        # Counts by type
        type_query = (
            select(
                FraudAlert.alert_type,
                func.count(FraudAlert.id).label("count"),
            )
            .where(base_filter)
            .group_by(FraudAlert.alert_type)
        )
        type_result = await self.db.execute(type_query)
        by_type = {row.alert_type: row.count for row in type_result.fetchall()}

        # Unresolved critical/high alerts
        unresolved_statuses = [
            FraudAlertStatus.NEW.value,
            FraudAlertStatus.INVESTIGATING.value,
        ]

        critical_unresolved_query = select(func.count(FraudAlert.id)).where(
            and_(
                base_filter,
                FraudAlert.severity == FraudAlertSeverity.CRITICAL.value,
                FraudAlert.status.in_(unresolved_statuses),
            )
        )
        critical_result = await self.db.execute(critical_unresolved_query)
        critical_unresolved = critical_result.scalar() or 0

        high_unresolved_query = select(func.count(FraudAlert.id)).where(
            and_(
                base_filter,
                FraudAlert.severity == FraudAlertSeverity.HIGH.value,
                FraudAlert.status.in_(unresolved_statuses),
            )
        )
        high_result = await self.db.execute(high_unresolved_query)
        high_unresolved = high_result.scalar() or 0

        # Average resolution time (for resolved alerts)
        resolution_time_query = select(
            func.avg(
                func.extract(
                    "epoch",
                    FraudAlert.resolved_at - FraudAlert.created_at
                ) / 3600
            )
        ).where(
            and_(
                base_filter,
                FraudAlert.resolved_at.isnot(None),
            )
        )
        resolution_result = await self.db.execute(resolution_time_query)
        avg_resolution_hours = resolution_result.scalar()

        summary = {
            "venue_id": str(venue_id),
            "date_from": str(date_from),
            "date_to": str(date_to),
            "total_alerts": total_alerts,
            "new_alerts": by_status.get(FraudAlertStatus.NEW.value, 0),
            "investigating_alerts": by_status.get(FraudAlertStatus.INVESTIGATING.value, 0),
            "confirmed_alerts": by_status.get(FraudAlertStatus.CONFIRMED.value, 0),
            "dismissed_alerts": by_status.get(FraudAlertStatus.DISMISSED.value, 0),
            "resolved_alerts": by_status.get(FraudAlertStatus.RESOLVED.value, 0),
            "by_type": [
                {"alert_type": k, "count": v} for k, v in by_type.items()
            ],
            "by_severity": [
                {"severity": k, "count": v} for k, v in by_severity.items()
            ],
            "by_status": [
                {"status": k, "count": v} for k, v in by_status.items()
            ],
            "critical_unresolved": critical_unresolved,
            "high_unresolved": high_unresolved,
            "average_resolution_hours": (
                round(avg_resolution_hours, 2) if avg_resolution_hours else None
            ),
        }

        logger.info(
            "fraud_summary_generated",
            venue_id=str(venue_id),
            date_from=str(date_from),
            date_to=str(date_to),
            total_alerts=total_alerts,
        )

        return summary


class FraudDetectionService:
    """
    Service for detecting and managing fraud alerts in POS operations.

    This service provides comprehensive fraud detection capabilities including
    real-time transaction analysis, batch processing for daily reports, and
    alert lifecycle management.

    Attributes:
        db: AsyncSession for database operations.
        event_publisher: Optional EventPublisher for sending alert notifications.
        rules: List of FraudRule configurations for detection.
    """

    def __init__(
        self,
        db: AsyncSession,
        event_publisher: Optional[EventPublisher] = None,
        rules: Optional[List[FraudRule]] = None,
    ) -> None:
        """
        Initialize the fraud detection service.

        Args:
            db: SQLAlchemy async session for database operations.
            event_publisher: Optional publisher for fraud alert events.
            rules: Optional list of custom fraud rules. Defaults to DEFAULT_FRAUD_RULES.
        """
        self.db = db
        self.event_publisher = event_publisher
        self.rules = rules or DEFAULT_FRAUD_RULES

    # =========================================================================
    # Alert Management
    # =========================================================================

    async def get_alert(self, alert_id: uuid.UUID) -> FraudAlert:
        """
        Retrieve a fraud alert by ID.

        Args:
            alert_id: The UUID of the fraud alert to retrieve.

        Returns:
            The FraudAlert instance.

        Raises:
            ServiceError: If the alert is not found (FRAUD_ALERT_NOT_FOUND).
        """
        result = await self.db.execute(
            select(FraudAlert).where(FraudAlert.id == alert_id)
        )
        alert = result.scalars().first()
        if not alert:
            raise not_found(
                ErrorCode.FRAUD_ALERT_NOT_FOUND,
                f"Fraud alert {alert_id} not found",
            )
        return alert

    async def list_alerts(
        self,
        venue_id: uuid.UUID,
        status: Optional[FraudAlertStatus] = None,
        severity: Optional[FraudAlertSeverity] = None,
        date_from: Optional[date] = None,
        date_to: Optional[date] = None,
        skip: int = 0,
        limit: int = 50,
    ) -> List[FraudAlert]:
        """
        List fraud alerts for a venue with optional filtering.

        Args:
            venue_id: The venue to list alerts for.
            status: Optional filter by alert status.
            severity: Optional filter by alert severity.
            date_from: Optional start date filter (inclusive).
            date_to: Optional end date filter (inclusive).
            skip: Number of records to skip for pagination.
            limit: Maximum number of records to return.

        Returns:
            List of FraudAlert instances matching the criteria.
        """
        query = select(FraudAlert).where(FraudAlert.venue_id == venue_id)

        if status:
            query = query.where(FraudAlert.status == status.value)
        if severity:
            query = query.where(FraudAlert.severity == severity.value)
        if date_from:
            query = query.where(
                func.date(FraudAlert.created_at) >= date_from
            )
        if date_to:
            query = query.where(
                func.date(FraudAlert.created_at) <= date_to
            )

        query = query.order_by(FraudAlert.created_at.desc())
        query = query.offset(skip).limit(limit)

        result = await self.db.execute(query)
        alerts = list(result.scalars().all())

        logger.info(
            "fraud_alerts_listed",
            venue_id=str(venue_id),
            count=len(alerts),
            status=status.value if status else None,
            severity=severity.value if severity else None,
        )

        return alerts

    async def update_alert_status(
        self,
        alert_id: uuid.UUID,
        status: FraudAlertStatus,
        notes: Optional[str] = None,
        resolved_by: Optional[uuid.UUID] = None,
    ) -> FraudAlert:
        """
        Update the status of a fraud alert.

        Handles status transitions and resolution tracking. When resolving
        an alert, the resolved_at timestamp and resolved_by user are recorded.
        Publishes FRAUD_ALERT_RESOLVED event when an alert is resolved.

        Args:
            alert_id: The UUID of the alert to update.
            status: The new status to set.
            notes: Optional resolution or investigation notes.
            resolved_by: UUID of the user resolving the alert (required for RESOLVED status).

        Returns:
            The updated FraudAlert instance.

        Raises:
            ServiceError: If the alert is not found.
        """
        alert = await self.get_alert(alert_id)
        old_status = alert.status
        previous_severity = alert.severity

        alert.status = status.value

        if notes:
            alert.resolution_notes = notes

        # Handle resolution
        if status in (FraudAlertStatus.RESOLVED, FraudAlertStatus.DISMISSED):
            alert.resolved_at = datetime.utcnow()
            if resolved_by:
                alert.resolved_by = resolved_by

        await self.db.commit()
        await self.db.refresh(alert)

        logger.info(
            "fraud_alert_status_updated",
            alert_id=str(alert_id),
            venue_id=str(alert.venue_id),
            old_status=old_status,
            new_status=status.value,
        )

        # Publish resolution event
        if self.event_publisher and status in (
            FraudAlertStatus.RESOLVED,
            FraudAlertStatus.DISMISSED,
        ):
            await self.event_publisher.publish(
                EventType.FRAUD_ALERT_RESOLVED,
                {
                    "alert_id": str(alert.id),
                    "venue_id": str(alert.venue_id),
                    "alert_type": alert.alert_type,
                    "severity": alert.severity,
                    "status": status.value,
                    "resolved_by": str(resolved_by) if resolved_by else None,
                },
                venue_id=alert.venue_id,
            )

        # Publish escalation event if severity indicates escalation
        if self.event_publisher and status == FraudAlertStatus.CONFIRMED:
            await self.event_publisher.publish(
                EventType.FRAUD_ALERT_ESCALATED,
                {
                    "alert_id": str(alert.id),
                    "venue_id": str(alert.venue_id),
                    "alert_type": alert.alert_type,
                    "severity": alert.severity,
                    "previous_status": old_status,
                    "new_status": status.value,
                },
                venue_id=alert.venue_id,
            )

        return alert

    async def assign_alert(
        self,
        alert_id: uuid.UUID,
        assigned_to: uuid.UUID,
    ) -> FraudAlert:
        """
        Assign a fraud alert to a user for investigation.

        Args:
            alert_id: The UUID of the alert to assign.
            assigned_to: The UUID of the user to assign the alert to.

        Returns:
            The updated FraudAlert instance.

        Raises:
            ServiceError: If the alert is not found.
        """
        alert = await self.get_alert(alert_id)

        alert.assigned_to = assigned_to
        # Auto-transition to investigating when assigned
        if alert.status == FraudAlertStatus.NEW.value:
            alert.status = FraudAlertStatus.INVESTIGATING.value

        await self.db.commit()
        await self.db.refresh(alert)

        logger.info(
            "fraud_alert_assigned",
            alert_id=str(alert_id),
            venue_id=str(alert.venue_id),
            assigned_to=str(assigned_to),
        )

        return alert


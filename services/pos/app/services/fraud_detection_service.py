    async def check_high_void_rate(
        self,
        venue_id: uuid.UUID,
        cashier_id: uuid.UUID,
        threshold: float = 0.1,
    ) -> Optional[FraudAlert]:
        """
        Check if a cashier has a high void rate.

        Calculates the ratio of voided transactions to total transactions
        for the cashier and creates an alert if the rate exceeds the threshold.

        Args:
            venue_id: The venue to check.
            cashier_id: The cashier to analyze.
            threshold: Maximum acceptable void rate (default 0.1 = 10%).

        Returns:
            FraudAlert if threshold exceeded, None otherwise.
        """
        # Get transaction counts for the cashier in the last 24 hours
        since = datetime.utcnow() - timedelta(hours=24)

        total_query = select(func.count(Transaction.id)).where(
            and_(
                Transaction.venue_id == venue_id,
                Transaction.cashier_id == cashier_id,
                Transaction.created_at >= since,
            )
        )
        total_result = await self.db.execute(total_query)
        total_transactions = total_result.scalar() or 0

        if total_transactions < 10:
            # Not enough data to determine void rate
            return None

        voided_query = select(func.count(Transaction.id)).where(
            and_(
                Transaction.venue_id == venue_id,
                Transaction.cashier_id == cashier_id,
                Transaction.created_at >= since,
                Transaction.status == TransactionStatus.VOIDED.value,
            )
        )
        voided_result = await self.db.execute(voided_query)
        voided_transactions = voided_result.scalar() or 0

        void_rate = voided_transactions / total_transactions

        if void_rate > threshold:
            logger.warning(
                "high_void_rate_detected",
                venue_id=str(venue_id),
                cashier_id=str(cashier_id),
                void_rate=void_rate,
                threshold=threshold,
            )

            return await self._create_alert(
                venue_id=venue_id,
                alert_type="high_void_rate",
                severity=FraudAlertSeverity.HIGH,
                title=f"High void rate detected: {void_rate:.1%}",
                description=(
                    f"Cashier has a void rate of {void_rate:.1%} "
                    f"({voided_transactions} voided out of {total_transactions} transactions) "
                    f"in the last 24 hours, exceeding the threshold of {threshold:.1%}."
                ),
                detection_data={
                    "total_transactions": total_transactions,
                    "voided_transactions": voided_transactions,
                    "void_rate": float(void_rate),
                    "period_hours": 24,
                },
                entity_type="cashier",
                entity_id=cashier_id,
                threshold_value=Decimal(str(threshold)),
                actual_value=Decimal(str(void_rate)),
            )

        return None

    async def check_unusual_refund_pattern(
        self,
        venue_id: uuid.UUID,
        cashier_id: uuid.UUID,
        hours: int = 24,
        threshold: int = 5,
    ) -> Optional[FraudAlert]:
        """
        Check for unusual refund patterns by a cashier.

        Analyzes refund frequency and amounts to detect suspicious patterns
        that may indicate fraudulent activity.

        Args:
            venue_id: The venue to check.
            cashier_id: The cashier to analyze.
            hours: Time window to analyze (default 24 hours).
            threshold: Maximum number of refunds before alert (default 5).

        Returns:
            FraudAlert if unusual pattern detected, None otherwise.
        """
        since = datetime.utcnow() - timedelta(hours=hours)

        # Count refunds processed by this cashier (via transaction)
        refund_query = (
            select(
                func.count(Refund.id).label("refund_count"),
                func.coalesce(func.sum(Refund.refund_amount), Decimal("0")).label("total_amount"),
            )
            .select_from(Refund)
            .join(Transaction, Transaction.id == Refund.transaction_id)
            .where(
                and_(
                    Transaction.venue_id == venue_id,
                    Transaction.cashier_id == cashier_id,
                    Refund.created_at >= since,
                    Refund.status.in_([
                        RefundStatus.APPROVED.value,
                        RefundStatus.PROCESSED.value,
                    ]),
                )
            )
        )

        result = await self.db.execute(refund_query)
        row = result.one()
        refund_count = row.refund_count or 0
        total_amount = row.total_amount or Decimal("0")

        if refund_count > threshold:
            logger.warning(
                "unusual_refund_pattern_detected",
                venue_id=str(venue_id),
                cashier_id=str(cashier_id),
                refund_count=refund_count,
                total_amount=str(total_amount),
                threshold=threshold,
            )

            return await self._create_alert(
                venue_id=venue_id,
                alert_type="unusual_refunds",
                severity=FraudAlertSeverity.MEDIUM,
                title=f"Unusual refund pattern: {refund_count} refunds",
                description=(
                    f"Cashier has processed {refund_count} refunds totaling ${total_amount:.2f} "
                    f"in the last {hours} hours, exceeding the threshold of {threshold} refunds."
                ),
                detection_data={
                    "refund_count": refund_count,
                    "total_amount": str(total_amount),
                    "period_hours": hours,
                },
                entity_type="cashier",
                entity_id=cashier_id,
                threshold_value=Decimal(str(threshold)),
                actual_value=Decimal(str(refund_count)),
            )

        return None

    async def check_after_hours_transaction(
        self,
        venue_id: uuid.UUID,
        transaction_id: uuid.UUID,
        business_hours: Tuple[int, int] = (9, 22),
    ) -> Optional[FraudAlert]:
        """
        Check if a transaction occurred outside business hours.

        Args:
            venue_id: The venue to check.
            transaction_id: The transaction to analyze.
            business_hours: Tuple of (start_hour, end_hour) in 24-hour format.
                           Default is 9 AM to 10 PM.

        Returns:
            FraudAlert if transaction is outside business hours, None otherwise.
        """
        result = await self.db.execute(
            select(Transaction).where(Transaction.id == transaction_id)
        )
        transaction = result.scalars().first()

        if not transaction:
            return None

        transaction_hour = transaction.created_at.hour
        start_hour, end_hour = business_hours

        if transaction_hour < start_hour or transaction_hour >= end_hour:
            logger.warning(
                "after_hours_transaction_detected",
                venue_id=str(venue_id),
                transaction_id=str(transaction_id),
                transaction_hour=transaction_hour,
                business_hours=business_hours,
            )

            return await self._create_alert(
                venue_id=venue_id,
                alert_type="after_hours",
                severity=FraudAlertSeverity.LOW,
                title=f"After-hours transaction at {transaction_hour}:00",
                description=(
                    f"Transaction occurred at {transaction.created_at.strftime('%H:%M')} "
                    f"which is outside business hours ({start_hour}:00 - {end_hour}:00). "
                    f"Amount: ${transaction.total_amount:.2f}"
                ),
                detection_data={
                    "transaction_hour": transaction_hour,
                    "business_hours_start": start_hour,
                    "business_hours_end": end_hour,
                    "transaction_time": transaction.created_at.isoformat(),
                    "amount": str(transaction.total_amount),
                },
                entity_type="transaction",
                entity_id=transaction_id,
            )

        return None

    async def check_large_discount(
        self,
        venue_id: uuid.UUID,
        transaction_id: uuid.UUID,
        discount_threshold_percent: float = 50,
    ) -> Optional[FraudAlert]:
        """
        Check if a transaction has an unusually large discount.

        Args:
            venue_id: The venue to check.
            transaction_id: The transaction to analyze.
            discount_threshold_percent: Maximum acceptable discount percentage.
                                       Default is 50%.

        Returns:
            FraudAlert if discount exceeds threshold, None otherwise.
        """
        result = await self.db.execute(
            select(Transaction).where(Transaction.id == transaction_id)
        )
        transaction = result.scalars().first()

        if not transaction or transaction.subtotal == 0:
            return None

        discount_percent = (
            float(transaction.discount_amount) / float(transaction.subtotal)
        ) * 100

        if discount_percent > discount_threshold_percent:
            logger.warning(
                "large_discount_detected",
                venue_id=str(venue_id),
                transaction_id=str(transaction_id),
                discount_percent=discount_percent,
                threshold=discount_threshold_percent,
            )

            return await self._create_alert(
                venue_id=venue_id,
                alert_type="large_discount",
                severity=FraudAlertSeverity.MEDIUM,
                title=f"Large discount applied: {discount_percent:.1f}%",
                description=(
                    f"Transaction has a discount of ${transaction.discount_amount:.2f} "
                    f"({discount_percent:.1f}%) on a subtotal of ${transaction.subtotal:.2f}, "
                    f"exceeding the threshold of {discount_threshold_percent}%."
                ),
                detection_data={
                    "subtotal": str(transaction.subtotal),
                    "discount_amount": str(transaction.discount_amount),
                    "discount_percent": discount_percent,
                    "cashier_id": str(transaction.cashier_id) if transaction.cashier_id else None,
                },
                entity_type="transaction",
                entity_id=transaction_id,
                threshold_value=Decimal(str(discount_threshold_percent)),
                actual_value=Decimal(str(discount_percent)),
            )

        return None

    async def check_excessive_comps(
        self,
        venue_id: uuid.UUID,
        cashier_id: uuid.UUID,
        hours: int = 8,
        threshold: int = 3,
    ) -> Optional[FraudAlert]:
        """
        Check for excessive complimentary (comp) transactions by a cashier.

        Args:
            venue_id: The venue to check.
            cashier_id: The cashier to analyze.
            hours: Time window to analyze (default 8 hours / one shift).
            threshold: Maximum number of comps before alert (default 3).

        Returns:
            FraudAlert if excessive comps detected, None otherwise.
        """
        since = datetime.utcnow() - timedelta(hours=hours)

        # Count comp payments processed by this cashier
        comp_query = (
            select(
                func.count(Payment.id).label("comp_count"),
                func.coalesce(func.sum(Payment.amount), Decimal("0")).label("total_amount"),
            )
            .select_from(Payment)
            .join(Transaction, Transaction.id == Payment.transaction_id)
            .where(
                and_(
                    Transaction.venue_id == venue_id,
                    Transaction.cashier_id == cashier_id,
                    Payment.created_at >= since,
                    Payment.payment_method == PaymentMethod.COMP.value,
                    Payment.status == PaymentStatus.COMPLETED.value,
                )
            )
        )

        result = await self.db.execute(comp_query)
        row = result.one()
        comp_count = row.comp_count or 0
        total_amount = row.total_amount or Decimal("0")

        if comp_count > threshold:
            logger.warning(
                "excessive_comps_detected",
                venue_id=str(venue_id),
                cashier_id=str(cashier_id),
                comp_count=comp_count,
                total_amount=str(total_amount),
                threshold=threshold,
            )

            return await self._create_alert(
                venue_id=venue_id,
                alert_type="excessive_comps",
                severity=FraudAlertSeverity.HIGH,
                title=f"Excessive comps: {comp_count} complimentary transactions",
                description=(
                    f"Cashier has processed {comp_count} complimentary transactions "
                    f"totaling ${total_amount:.2f} in the last {hours} hours, "
                    f"exceeding the threshold of {threshold}."
                ),
                detection_data={
                    "comp_count": comp_count,
                    "total_amount": str(total_amount),
                    "period_hours": hours,
                },
                entity_type="cashier",
                entity_id=cashier_id,
                threshold_value=Decimal(str(threshold)),
                actual_value=Decimal(str(comp_count)),
            )

        return None

    async def check_cash_drawer_variance(
        self,
        venue_id: uuid.UUID,
        drawer_id: uuid.UUID,
        threshold: Decimal = Decimal("20.00"),
    ) -> Optional[FraudAlert]:
        """
        Check if a cash drawer has a significant variance.

        Args:
            venue_id: The venue to check.
            drawer_id: The cash drawer to analyze.
            threshold: Maximum acceptable variance amount (default $20).

        Returns:
            FraudAlert if variance exceeds threshold, None otherwise.
        """
        result = await self.db.execute(
            select(CashDrawer).where(CashDrawer.id == drawer_id)
        )
        drawer = result.scalars().first()

        if not drawer or drawer.variance is None:
            return None

        variance_abs = abs(drawer.variance)

        if variance_abs > threshold:
            variance_type = "shortage" if drawer.variance < 0 else "overage"

            logger.warning(
                "cash_drawer_variance_detected",
                venue_id=str(venue_id),
                drawer_id=str(drawer_id),
                variance=str(drawer.variance),
                threshold=str(threshold),
            )

            return await self._create_alert(
                venue_id=venue_id,
                alert_type="cash_drawer_variance",
                severity=FraudAlertSeverity.HIGH,
                title=f"Cash drawer {variance_type}: ${variance_abs:.2f}",
                description=(
                    f"Cash drawer has a {variance_type} of ${variance_abs:.2f}. "
                    f"Expected: ${drawer.expected_cash:.2f}, "
                    f"Actual: ${drawer.closing_cash:.2f}. "
                    f"Terminal: {drawer.terminal_id}"
                ),
                detection_data={
                    "opening_cash": str(drawer.opening_cash),
                    "expected_cash": str(drawer.expected_cash),
                    "closing_cash": str(drawer.closing_cash),
                    "variance": str(drawer.variance),
                    "variance_type": variance_type,
                    "terminal_id": drawer.terminal_id,
                    "cashier_id": str(drawer.cashier_id),
                },
                entity_type="terminal",
                entity_id=drawer_id,
                threshold_value=threshold,
                actual_value=variance_abs,
            )

        return None

    async def check_split_transactions(
        self,
        venue_id: uuid.UUID,
        time_window_minutes: int = 5,
        amount_threshold: Decimal = Decimal("100"),
    ) -> List[FraudAlert]:
        """
        Check for potential split transaction patterns (structuring).

        Detects multiple smaller transactions that may be intentionally
        split to avoid thresholds or oversight.

        Args:
            venue_id: The venue to check.
            time_window_minutes: Time window to group transactions.
            amount_threshold: Minimum combined amount to trigger alert.

        Returns:
            List of FraudAlerts for detected split patterns.
        """
        # Look at transactions in the last 24 hours
        since = datetime.utcnow() - timedelta(hours=24)
        alerts: List[FraudAlert] = []

        # Find cashiers with multiple transactions close together
        # This is a simplified check - production might use more sophisticated analysis
        subquery = (
            select(
                Transaction.cashier_id,
                Transaction.customer_id,
                func.count(Transaction.id).label("txn_count"),
                func.sum(Transaction.total_amount).label("total_amount"),
            )
            .where(
                and_(
                    Transaction.venue_id == venue_id,
                    Transaction.created_at >= since,
                    Transaction.status == TransactionStatus.COMPLETED.value,
                    Transaction.cashier_id.isnot(None),
                )
            )
            .group_by(
                Transaction.cashier_id,
                Transaction.customer_id,
                func.date_trunc("hour", Transaction.created_at),
            )
            .having(
                and_(
                    func.count(Transaction.id) >= 3,
                    func.sum(Transaction.total_amount) >= amount_threshold,
                )
            )
        )

        result = await self.db.execute(subquery)
        suspicious_patterns = result.fetchall()

        for pattern in suspicious_patterns:
            cashier_id = pattern.cashier_id
            customer_id = pattern.customer_id
            txn_count = pattern.txn_count
            total_amount = pattern.total_amount

            logger.warning(
                "split_transactions_detected",
                venue_id=str(venue_id),
                cashier_id=str(cashier_id) if cashier_id else None,
                customer_id=str(customer_id) if customer_id else None,
                txn_count=txn_count,
                total_amount=str(total_amount),
            )

            alert = await self._create_alert(
                venue_id=venue_id,
                alert_type="split_transactions",
                severity=FraudAlertSeverity.CRITICAL,
                title=f"Potential split transactions: {txn_count} transactions",
                description=(
                    f"Detected {txn_count} transactions totaling ${total_amount:.2f} "
                    f"within a short time period, which may indicate transaction structuring. "
                    f"Customer: {customer_id if customer_id else 'Unknown'}"
                ),
                detection_data={
                    "transaction_count": txn_count,
                    "total_amount": str(total_amount),
                    "time_window_minutes": time_window_minutes,
                    "customer_id": str(customer_id) if customer_id else None,
                },
                entity_type="cashier",
                entity_id=cashier_id,
                threshold_value=amount_threshold,
                actual_value=total_amount,
            )
            alerts.append(alert)

        return alerts

    async def check_repeated_voids(
        self,
        venue_id: uuid.UUID,
        cashier_id: uuid.UUID,
        hours: int = 4,
        threshold: int = 3,
    ) -> Optional[FraudAlert]:
        """
        Check for repeated void patterns by a cashier within a short period.

        Args:
            venue_id: The venue to check.
            cashier_id: The cashier to analyze.
            hours: Time window to analyze (default 4 hours).
            threshold: Maximum number of voids before alert (default 3).

        Returns:
            FraudAlert if repeated voids detected, None otherwise.
        """
        since = datetime.utcnow() - timedelta(hours=hours)

        void_query = select(
            func.count(Transaction.id).label("void_count"),
            func.coalesce(func.sum(Transaction.total_amount), Decimal("0")).label("total_amount"),
        ).where(
            and_(
                Transaction.venue_id == venue_id,
                Transaction.cashier_id == cashier_id,
                Transaction.created_at >= since,
                Transaction.status == TransactionStatus.VOIDED.value,
            )
        )

        result = await self.db.execute(void_query)
        row = result.one()
        void_count = row.void_count or 0
        total_amount = row.total_amount or Decimal("0")

        if void_count >= threshold:
            logger.warning(
                "repeated_voids_detected",
                venue_id=str(venue_id),
                cashier_id=str(cashier_id),
                void_count=void_count,
                total_amount=str(total_amount),
                threshold=threshold,
            )

            return await self._create_alert(
                venue_id=venue_id,
                alert_type="repeated_voids",
                severity=FraudAlertSeverity.MEDIUM,
                title=f"Repeated voids: {void_count} in {hours} hours",
                description=(
                    f"Cashier has voided {void_count} transactions "
                    f"totaling ${total_amount:.2f} in the last {hours} hours, "
                    f"which exceeds the threshold of {threshold}."
                ),
                detection_data={
                    "void_count": void_count,
                    "total_amount": str(total_amount),
                    "period_hours": hours,
                },
                entity_type="cashier",
                entity_id=cashier_id,
                threshold_value=Decimal(str(threshold)),
                actual_value=Decimal(str(void_count)),
            )

        return None


    async def _create_alert(
        self,
        venue_id: uuid.UUID,
        alert_type: str,
        severity: FraudAlertSeverity,
        title: str,
        description: str,
        detection_data: Dict[str, Any],
        entity_type: Optional[str] = None,
        entity_id: Optional[uuid.UUID] = None,
        threshold_value: Optional[Decimal] = None,
        actual_value: Optional[Decimal] = None,
    ) -> FraudAlert:
        """
        Create a new fraud alert and publish the creation event.

        This is an internal helper method used by all detection checks
        to create consistent alert records.

        Args:
            venue_id: The venue the alert belongs to.
            alert_type: Type identifier for the alert.
            severity: Severity level of the alert.
            title: Short summary title for the alert.
            description: Detailed description of the detected issue.
            detection_data: Raw data that triggered the alert.
            entity_type: Optional type of entity involved.
            entity_id: Optional ID of the entity involved.
            threshold_value: Optional threshold that was exceeded.
            actual_value: Optional actual value that triggered the alert.

        Returns:
            The newly created FraudAlert instance.
        """
        alert = FraudAlert(
            venue_id=venue_id,
            alert_type=alert_type,
            severity=severity.value,
            status=FraudAlertStatus.NEW.value,
            entity_type=entity_type,
            entity_id=entity_id,
            title=title,
            description=description,
            detection_data=detection_data,
            threshold_value=threshold_value,
            actual_value=actual_value,
        )

        self.db.add(alert)
        await self.db.commit()
        await self.db.refresh(alert)

        logger.info(
            "fraud_alert_created",
            alert_id=str(alert.id),
            venue_id=str(venue_id),
            alert_type=alert_type,
            severity=severity.value,
            entity_type=entity_type,
            entity_id=str(entity_id) if entity_id else None,
        )

        # Publish event
        if self.event_publisher:
            await self.event_publisher.publish(
                EventType.FRAUD_ALERT_CREATED,
                {
                    "alert_id": str(alert.id),
                    "venue_id": str(venue_id),
                    "alert_type": alert_type,
                    "severity": severity.value,
                    "title": title,
                    "entity_type": entity_type,
                    "entity_id": str(entity_id) if entity_id else None,
                },
                venue_id=venue_id,
            )

        return alert

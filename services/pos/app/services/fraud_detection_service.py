"""
=============================================================================
FILE: services/fraud_detection_service.py
PURPOSE: Advanced fraud detection service for the POS Integration Service
=============================================================================

Provides comprehensive fraud detection capabilities for point-of-sale operations.
This service implements multiple detection strategies to identify suspicious activity
including:

- High void rates by cashier
- Unusual refund patterns
- After-hours transactions
- Large discounts exceeding thresholds
- Excessive complimentary transactions
- Cash drawer variance analysis
- Split transaction detection (structuring)
- Repeated void patterns

The service supports:
- Real-time fraud checks on individual transactions
- Batch analysis for daily fraud reports
- Alert management and investigation workflow
- Event publishing for alert notifications

Detection rules are configurable via FraudRule dataclass and can be extended
to support venue-specific thresholds.
"""

